// The rules take angles in radians, 0 along x and a quarter turn along y,
// which on the field, its y running down, is clockwise; tuning gives them in
// degrees, which read more easily.

/** A whole turn, in radians. */
export const TURN = 2 * Math.PI;

/** The radians in a degree. */
export const RADIANS_PER_DEGREE = Math.PI / 180;
