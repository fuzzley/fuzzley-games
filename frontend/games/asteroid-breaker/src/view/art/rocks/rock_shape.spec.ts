/** Returns a number to four places, as the kit's are copied, a zero below it unsigned. */
function fourPlaces(value: number): number {
  return Math.round(value * 1e4) / 1e4 + 0;
}

/** Returns points as a flat list to four places, as the kit's are copied. */
function flat(points: readonly Point[]): readonly number[] {
  return points.flatMap(({ x, y }) => [fourPlaces(x), fourPlaces(y)]);
}

/** Returns a rock as the kit's numbers are copied, without its kind. */
function copied(rock: RockShape): unknown {
  return {
    size: rock.size,
    outline: flat(rock.outline),
    rim: flat(rock.rim),
    facets: rock.facets.map(({ part, facing, points }) => ({
      part,
      facing: [facing.x, facing.y, facing.z].map(fourPlaces),
      points: flat(points),
    })),
    lines: rock.lines.map(({ tone, width, points }) => ({
      tone,
      width: fourPlaces(width),
      points: flat(points),
    })),
    dots: rock.dots.map(({ tone, r, at }) => ({
      tone,
      r: fourPlaces(r),
      at: flat([at]),
    })),
    glows: rock.glows.map(({ tone, r, strength, at }) => ({
      tone,
      r: fourPlaces(r),
      strength: fourPlaces(strength),
      at: flat([at]),
    })),
    aura: rock.aura.map(({ tone, width, points }) => ({
      tone,
      width: fourPlaces(width),
      points: flat(points),
    })),
  };
}

/** Returns the sum of numbers, in order. */
function sum(values: readonly number[]): number {
  return values.reduce((total, value) => total + value, 0);
}

/** Returns a rock in brief, as the kit's other cuts are copied. */
function brief(rock: RockShape): unknown {
  const corners = rock.facets.flatMap(({ points }) => points);
  const marks = [...rock.lines, ...rock.aura].flatMap(({ points }) => points);
  return {
    kind: rock.kind,
    size: rock.size,
    outline: flat(rock.outline),
    facets: rock.facets.length,
    corners: [
      sum(corners.map(({ x }) => x)),
      sum(corners.map(({ y }) => y)),
    ].map(fourPlaces),
    facings: [
      sum(rock.facets.map(({ facing }) => facing.x)),
      sum(rock.facets.map(({ facing }) => facing.y)),
      sum(rock.facets.map(({ facing }) => facing.z)),
    ].map(fourPlaces),
    lines: rock.lines.length,
    aura: rock.aura.length,
    marks: [sum(marks.map(({ x }) => x)), sum(marks.map(({ y }) => y))].map(
      fourPlaces,
    ),
    dots: rock.dots.flatMap(({ at, r }) => [at.x, at.y, r].map(fourPlaces)),
    glows: rock.glows.length,
  };
}

/** Each kind's sizes, as the catalog gives its hits at each. */
function sizesOf(kind: RockKindId): readonly RockSize[] {
  return ROCK_SIZES.filter((size) => rockKind(kind).hits[size] !== undefined);
}

