/**
 * Holds Fuzz Flux's thirty-six draft levels as pictures.
 *
 * A square of a board's picture is a letter: `.` a fuzzball of any kind, `_`
 * no square, `1` to `4` a brick with that many hits, a kind's letter
 * (b, r, a, g, v, p) a fuzzball of that kind and its capital the same in a
 * cage, `?` a caged fuzzball of any kind, `*` one with a burr, `z` a
 * sleepyhead. A dust picture has a digit a square, the layers of dust on it.
 */

