/**
 * Returns every level in order, each with its number and its set.
 * @returns {(Draft & { id: number, set: string })[]}
 */
export function allLevels() {
  let id = 0;
  return SETS.flatMap((set) =>
    set.levels.map((level) => ({ ...level, id: ++id, set: set.id })),
  );
}
